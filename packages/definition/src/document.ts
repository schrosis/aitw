import type { Intermediate, IntermediateStep, Transition } from "@ugoke/core";

/** Line at the top of a generated document, which tells it from a file that someone wrote. */
export const documentMarker = "<!-- Generated by ugoke docs. Do not edit. -->";

const startNode = "start_";
const endNode = "end_";

/** Returns the ID of a step in a diagram. A prefix keeps it from a keyword such as `graph`. */
const nodeOf = (id: string): string => `s_${id}`;

const renderNode = (id: string, { type }: IntermediateStep): string => {
  const label = `"${id}"`;
  switch (type) {
    case "ai": {
      return `  ${nodeOf(id)}([${label}])`;
    }
    case "wait": {
      return `  ${nodeOf(id)}{{${label}}}`;
    }
    default: {
      return `  ${nodeOf(id)}[${label}]`;
    }
  }
};

const labelEntities: ReadonlyMap<string, string> = new Map([
  ['"', "#quot;"],
  ["<", "#lt;"],
  [">", "#gt;"],
]);

/** Writes characters that a quoted label cannot hold as entities of Mermaid. */
const escapeLabel = (text: string): string =>
  text.replaceAll(/["<>]/gu, (character) => labelEntities.get(character) ?? character);

/** Returns a condition without its `${{ }}`, on one line. */
const describeCondition = (condition: string): string =>
  condition
    .trim()
    .replace(/^\$\{\{/u, "")
    .replace(/\}\}$/u, "")
    .trim()
    .replaceAll(/\s+/gu, " ");

/** Splits a condition before each `&&` and `||` that is outside of parentheses and strings. */
const breakAtOperators = (expression: string): string[] => {
  const lines: string[] = [];
  let start = 0;
  let depth = 0;
  let quoted = false;
  for (let index = 0; index < expression.length; index += 1) {
    const character = expression[index];
    if (character === "'") {
      quoted = !quoted;
    } else if (!quoted && character === "(") {
      depth += 1;
    } else if (!quoted && character === ")") {
      depth -= 1;
    } else if (
      !quoted &&
      depth === 0 &&
      index > start &&
      (expression.startsWith("&&", index) || expression.startsWith("||", index))
    ) {
      lines.push(expression.slice(start, index).trim());
      start = index;
      index += 1;
    }
  }
  return [...lines, expression.slice(start).trim()];
};

/** Returns the label of a condition, with a line for each part that `&&` and `||` join. */
const conditionLabel = (condition: string): string =>
  breakAtOperators(describeCondition(condition)).map(escapeLabel).join("<br/>");

const targetOf = (transition: Extract<Transition, { type: "end" | "step" }>): string =>
  transition.type === "end" ? endNode : nodeOf(transition.step);

/** Returns the ID of the node of a condition. It cannot be the ID of a step, which has `s_`. */
const decisionOf = (id: string, index: number): string => `d_${id}_${index}`;

/** Returns the nodes of the conditions of a step. */
const renderDecisions = (id: string, next: Transition): string[] =>
  next.type === "branch"
    ? next.branches.flatMap(({ if: condition }, index) =>
        condition === undefined
          ? []
          : [`  ${decisionOf(id, index)}{"${conditionLabel(condition)}"}`],
      )
    : [];

/**
 * Returns the edges of a step.
 *
 * Branches are tried in order, so each condition leads to the next one when it does not hold.
 * The last branch has no condition, and is where the last condition leads otherwise.
 */
const renderEdges = (id: string, next: Transition): string[] => {
  if (next.type !== "branch") {
    return [`  ${nodeOf(id)} --> ${targetOf(next)}`];
  }
  const nodeOfBranch = (index: number): string | undefined => {
    const branch = next.branches[index];
    if (branch === undefined) {
      return undefined;
    }
    return branch.if === undefined ? targetOf(branch.to) : decisionOf(id, index);
  };
  return [
    `  ${nodeOf(id)} --> ${nodeOfBranch(0) ?? endNode}`,
    ...next.branches.flatMap(({ if: condition, to }, index) =>
      condition === undefined
        ? []
        : [
            `  ${decisionOf(id, index)} -->|"yes"| ${targetOf(to)}`,
            `  ${decisionOf(id, index)} -->|"no"| ${nodeOfBranch(index + 1) ?? endNode}`,
          ],
    ),
  ];
};

/** Renders a workflow as a Mermaid flowchart. */
export const renderMermaid = ({ start, steps }: Intermediate): string => {
  const entries = Object.entries(steps);
  return [
    "flowchart TD",
    `  ${startNode}(("start"))`,
    ...entries.flatMap(([id, step]) => [renderNode(id, step), ...renderDecisions(id, step.next)]),
    `  ${endNode}(("end"))`,
    `  ${startNode} --> ${nodeOf(start)}`,
    ...entries.flatMap(([id, step]) => renderEdges(id, step.next)),
  ].join("\n");
};

/** Renders the Markdown document of a workflow. */
export const renderWorkflowDocument = (intermediate: Intermediate): string =>
  `${documentMarker}\n\n\`\`\`mermaid\n${renderMermaid(intermediate)}\n\`\`\`\n`;
