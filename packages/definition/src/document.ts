import type { Intermediate, IntermediateStep, Transition } from "@aitw/core";

/** Line at the top of a generated document, which tells it from a file that someone wrote. */
export const documentMarker = "<!-- Generated by aitw docs. Do not edit. -->";

/** Longest condition that a diagram shows, in characters. */
const maxConditionLength = 50;

const startNode = "start_";
const endNode = "end_";

/** Returns the ID of a step in a diagram. A prefix keeps it from a keyword such as `graph`. */
const nodeOf = (id: string): string => `s_${id}`;

const renderNode = (id: string, { type }: IntermediateStep): string => {
  const label = `"${id}"`;
  switch (type) {
    case "ai": {
      return `  ${nodeOf(id)}([${label}])`;
    }
    case "wait": {
      return `  ${nodeOf(id)}{{${label}}}`;
    }
    default: {
      return `  ${nodeOf(id)}[${label}]`;
    }
  }
};

/** Writes characters that a label cannot hold as entities of Mermaid. */
const escapeLabel = (text: string): string =>
  text.replaceAll(/[#"&<>|]/gu, (character) => `#${character.codePointAt(0)};`);

/** Returns a condition without its `${{ }}`, on one line, and short enough for a diagram. */
const describeCondition = (condition: string): string => {
  const expression = condition
    .trim()
    .replace(/^\$\{\{/u, "")
    .replace(/\}\}$/u, "")
    .trim()
    .replaceAll(/\s+/gu, " ");
  const characters = Array.from(new Intl.Segmenter().segment(expression), ({ segment }) => segment);
  return characters.length > maxConditionLength
    ? `${characters.slice(0, maxConditionLength).join("")}…`
    : expression;
};

const targetOf = (transition: Extract<Transition, { type: "end" | "step" }>): string =>
  transition.type === "end" ? endNode : nodeOf(transition.step);

const renderEdges = (id: string, next: Transition): string[] => {
  if (next.type !== "branch") {
    return [`  ${nodeOf(id)} --> ${targetOf(next)}`];
  }
  return next.branches.map(({ if: condition, to }) => {
    const label = condition === undefined ? "else" : escapeLabel(describeCondition(condition));
    return `  ${nodeOf(id)} -->|"${label}"| ${targetOf(to)}`;
  });
};

/** Renders a workflow as a Mermaid flowchart. */
export const renderMermaid = ({ start, steps }: Intermediate): string => {
  const entries = Object.entries(steps);
  return [
    "flowchart TD",
    `  ${startNode}(("start"))`,
    ...entries.map(([id, step]) => renderNode(id, step)),
    `  ${endNode}(("end"))`,
    `  ${startNode} --> ${nodeOf(start)}`,
    ...entries.flatMap(([id, step]) => renderEdges(id, step.next)),
  ].join("\n");
};

/** Renders the Markdown document of a workflow. */
export const renderWorkflowDocument = (intermediate: Intermediate): string =>
  `${documentMarker}\n\n\`\`\`mermaid\n${renderMermaid(intermediate)}\n\`\`\`\n`;
