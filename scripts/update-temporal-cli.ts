/**
 * Pins the Temporal CLI release that aitw downloads, or checks the pinned release.
 *
 * Usage:
 *   node scripts/update-temporal-cli.ts <version>   Pin a release and its checksums
 *   node scripts/update-temporal-cli.ts --check     Check the pinned checksums against the release
 */
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import { temporalCliManifest } from "../packages/cli/src/temporal-cli/manifest.ts";
import { temporalCliPlatforms } from "../packages/cli/src/temporal-cli/types.ts";
import type {
  TemporalCliAsset,
  TemporalCliManifest,
  TemporalCliPlatform,
} from "../packages/cli/src/temporal-cli/types.ts";

const manifestPath = fileURLToPath(
  new URL("../packages/cli/src/temporal-cli/manifest.ts", import.meta.url),
);

/** Release names of the platforms, keyed by the platform names of Node.js. */
const platforms: Record<TemporalCliPlatform, string> = {
  "darwin-arm64": "darwin_arm64",
  "darwin-x64": "darwin_amd64",
  "linux-arm64": "linux_arm64",
  "linux-x64": "linux_amd64",
};

const fetchManifest = async (version: string): Promise<TemporalCliManifest> => {
  const url = `https://github.com/temporalio/cli/releases/download/v${version}/checksums.txt`;
  const response = await fetch(url);
  if (!response.ok) {
    throw new Error(`Failed to download ${url}: ${response.status}`);
  }
  const checksums = new Map(
    (await response.text())
      .trim()
      .split("\n")
      .map((line) => {
        const [sha256 = "", file = ""] = line.trim().split(/\s+/u);
        return [file, sha256] as const;
      }),
  );

  const asset = (platform: TemporalCliPlatform): TemporalCliAsset => {
    const file = `temporal_cli_${version}_${platforms[platform]}.tar.gz`;
    const sha256 = checksums.get(file);
    if (sha256 === undefined || !/^[0-9a-f]{64}$/u.test(sha256)) {
      throw new Error(`The release does not contain a checksum for ${file}`);
    }
    return { file, sha256 };
  };
  // Listing every platform makes the type checker report a platform that is not handled here.
  const assets: Record<TemporalCliPlatform, TemporalCliAsset> = {
    "darwin-arm64": asset("darwin-arm64"),
    "darwin-x64": asset("darwin-x64"),
    "linux-arm64": asset("linux-arm64"),
    "linux-x64": asset("linux-x64"),
  };
  return { assets, version };
};

const render = ({ assets, version }: TemporalCliManifest): string => {
  const lines = Object.entries(assets).map(
    ([platform, { file, sha256 }]) =>
      `    "${platform}": { file: "${file}", sha256: "${sha256}" },`,
  );
  return [
    "// This file is generated by scripts/update-temporal-cli.ts. Do not edit it by hand.",
    'import type { TemporalCliManifest } from "./types.js";',
    "",
    "/** The Temporal CLI release that aitw downloads for the development server. */",
    "export const temporalCliManifest: TemporalCliManifest = {",
    `  version: "${version}",`,
    "  assets: {",
    ...lines,
    "  },",
    "};",
    "",
  ].join("\n");
};

const [argument] = process.argv.slice(2);
if (argument === "--check") {
  const expected = await fetchManifest(temporalCliManifest.version);
  // Compare each platform, so that an archive pinned for another platform is detected.
  const matches = temporalCliPlatforms.every((platform) => {
    const pinned = temporalCliManifest.assets[platform];
    const { file, sha256 } = expected.assets[platform];
    return pinned.file === file && pinned.sha256 === sha256;
  });
  if (!matches) {
    console.error(
      `The pinned checksums do not match Temporal CLI ${temporalCliManifest.version}. ` +
        `Run: node scripts/update-temporal-cli.ts ${temporalCliManifest.version}`,
    );
    process.exitCode = 1;
  } else {
    console.log(`Temporal CLI ${temporalCliManifest.version} checksums match the release`);
  }
} else if (argument !== undefined && /^\d+\.\d+\.\d+$/u.test(argument)) {
  writeFileSync(manifestPath, render(await fetchManifest(argument)));
  execFileSync("pnpm", ["exec", "oxfmt", manifestPath], { stdio: "inherit" });
  console.log(`Pinned Temporal CLI ${argument}`);
} else {
  console.error("Usage: node scripts/update-temporal-cli.ts <version> | --check");
  process.exitCode = 1;
}
